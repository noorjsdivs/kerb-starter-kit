// Generates src/components/ui/icon-glyphs.ts from scripts/icons/glyphs.json.
const fs = require('fs');
const path = require('path');
const glyphs = JSON.parse(fs.readFileSync(path.join(__dirname, 'glyphs.json'), 'utf8'));
const lines = Object.entries(glyphs).map(([k, v]) => `  ${/^[a-z_][a-z0-9_]*$/.test(k) ? k : JSON.stringify(k)}: 0x${v.toString(16)},`);
const out = `// AUTO-GENERATED by scripts/icons/gen-glyphs.js — do not edit by hand.
// Material Symbols Rounded codepoints for the glyphs bundled in assets/fonts/KerbSymbols*.ttf.
// To add icons: append names to the \`extra\` list in scripts/icons/collect.py and follow scripts/icons/README.md.

export const GLYPHS = {
${lines.join('\n')}
} as const;

export type IconName = keyof typeof GLYPHS;
`;
fs.writeFileSync(path.join(__dirname, '../../src/components/ui/icon-glyphs.ts'), out);
console.log('glyphs:', Object.keys(glyphs).length);
